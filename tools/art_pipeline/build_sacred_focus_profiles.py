"""Recover staff-focus anchors in the exported GLB bone coordinate system.

Run inspect_sacred_focus.py with Blender first. Does not change any model.
"""
import json
from pathlib import Path
import numpy as np
from glb_pose_math import PoseModel

root = Path(__file__).resolve().parents[2]
uv_bounds = json.loads((root / 'art_source/sacred_focus_uv.json').read_text())
profiles = {}
for name, bounds in uv_bounds.items():
    model = PoseModel(next((root / 'assets/generated').rglob(name + '.glb')))
    points, ids, uv = model.geometry()
    source_uv = np.array(bounds['uvs'])
    source_uv[:, 1] = 1 - source_uv[:, 1]
    mask = (np.abs(uv[:, None, :] - source_uv[None, :, :]).max(axis=2) < 1e-6).any(axis=1) & (ids == model.names.index('hand_r'))
    assert mask.sum() >= 12, (name, mask.sum())
    joint = int(np.bincount(ids[mask]).argmax())
    assert model.names[joint] == 'hand_r', (name, model.names[joint])
    center = model.skinned(model.rest, points, ids)[mask].mean(axis=0)
    offset = (np.linalg.inv(model.rest[model.joints[joint]]) @ np.r_[center, 1])[:3]
    profiles[name] = {'bone': 'hand_r', 'offset': offset.tolist(), 'release_seconds': 1.1}
    print(name, 'vertices', mask.sum(), 'offset', offset.round(5).tolist())
out = root / 'assets/vfx/sacred/focus_profiles.json'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps(profiles, indent=2))
# A preloaded script embeds the anchors in exported games, without raw-file filters.
(root / 'scripts/vfx/SacredFocusProfiles.gd').write_text(
    '# Generated by tools/art_pipeline/build_sacred_focus_profiles.py.\n'
    'extends RefCounted\n\nconst PROFILES := ' + json.dumps(profiles, indent=2) + '\n')
