"""Map native GLB focuses into their animated bone coordinate system."""
import json
from pathlib import Path
import numpy as np
from glb_pose_math import PoseModel

root = Path(__file__).resolve().parents[2]
source = json.loads((root / 'art_source/school_focus_uv.json').read_text())
profiles = {}
for name, info in source.items():
    model = PoseModel(next((root / 'assets/generated').rglob(name + '.glb')))
    points, ids, uv = model.geometry()
    expected = np.array(info['uvs'])
    expected[:,1] = 1 - expected[:,1]
    hand = model.names.index('hand_r')
    mask = (np.abs(uv[:,None,:]-expected[None,:,:]).max(axis=2)<1e-6).any(axis=1) & (ids==hand)
    assert mask.sum() >= 12,(name,int(mask.sum()))
    center = model.skinned(model.rest,points,ids)[mask].mean(axis=0)
    offset = (np.linalg.inv(model.rest[model.joints[hand]]) @ np.r_[center,1])[:3]
    profiles[name] = {'bone':'hand_r','offset':offset.tolist(),'release_seconds':1.1}
    print(name,info['part'],int(mask.sum()))
assert len(profiles)==20
out = root / 'assets/vfx/schools'
out.mkdir(parents=True,exist_ok=True)
(out / 'focus_profiles.json').write_text(json.dumps(profiles,indent=2))
(root / 'scripts/vfx/SchoolFocusProfiles.gd').write_text('# Generated by build_school_focus_profiles.py; embedded in exported builds.\nextends RefCounted\n\nconst PROFILES := '+json.dumps(profiles,indent=2)+'\n')
