"""Embed UV islands of the existing staff tips; no bitmap or model is changed."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
profiles = {}
for filename in ['sacred_focus_uv.json', 'school_focus_uv.json']:
    for name, info in json.loads((root / 'art_source' / filename).read_text()).items():
        uv = info['uvs']
        assert len(uv) == 24, (name,len(uv))
        rectangles = []
        for i in range(0,len(uv),4):
            points = [(v[0],1-v[1]) for v in uv[i:i+4]]
            rectangles.append([min(v[0] for v in points),min(v[1] for v in points),max(v[0] for v in points),max(v[1] for v in points)])
        profiles[name] = rectangles
assert len(profiles) == 24
(root / 'scripts/vfx/FocusEmissionMasks.gd').write_text(
    '# Generated by build_focus_glow_masks.py from existing Blender UV islands.\n'
    'extends RefCounted\n\nconst MASKS := '+json.dumps(profiles,indent=2)+'\n')
print('FOCUS_MASKS',len(profiles))
